	filter jsonb,
	target_size integer,
	day_zero_on date,
	extension_on date,
	checkpoint1_on date,
	checkpoint2_on date,
	decisions_from_on date,
	decisions_to_on date,
	deadline_on date,
	created_by uuid,
	created_at timestamptz not null default now()
);
create index cohorts_status_idx on cohorts (status);

-- ---------- companies ----------
create table companies (
	ico char(8) primary key check (ico ~ '^[0-9]{8}$'),
	name text,
	name_search text not null default '',
	subject_type text check (subject_type in ('FO', 'PO')),
	legal_form_code text,
	region_code text,
	region_name text,
	district_code text,
	district_name text,
	nace_codes text[] not null default '{}',
	founded_on date,
	dissolved_on date,
	ico_valid boolean,
	ico_verified_at timestamptz,
	state text not null default 'v_poolu' check (state in (
		'v_poolu', 've_filtru', 'u_robota_ocisteni', 'superuser', 'login_oz', 'vraceno',
		'odvlastneno', 'plovak', 'karantena', 'ztraceno', 'zakaznik', 'neaktivni_ico')),
	holder_type text not null default 'neznamo'
		check (holder_type in ('superuser', 'login_oz', 'pool', 'jiny_partner', 'neznamo')),
	holder_login text,
	sales_rep_id integer references sales_reps (id),
	owned_from date,
	ownership_ends_on date,
	cohort_id integer references cohorts (id),
	channel text check (channel in ('operatorka', 'cold_call')),
	rounds_count smallint not null default 0,
	return_on date,
	return_path text check (return_path in ('siebel_check', 'robot')),
	quarantine_until date,
	never_return boolean not null default false,
	return_on_overridden boolean not null default false,
	return_on_override_note text,
	quarantine_overridden boolean not null default false,
	quarantine_override_note text,
	ca_number text,
	siebel_owner text,
	siebel_opportunity_valid_until date,
	siebel_checked_at timestamptz,
	raynet_company_id bigint,
	extra jsonb,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	constraint companies_return_override_note
		check (not return_on_overridden or length(trim(coalesce(return_on_override_note, ''))) > 0),
	constraint companies_quarantine_override_note
		check (not quarantine_overridden or length(trim(coalesce(quarantine_override_note, ''))) > 0)
);

-- Keeps name_search (lower-case, no diacritics) and updated_at in sync on every write.
create or replace function companies_before_write() returns trigger
language plpgsql as $$
begin
	new.name_search := search_norm(new.name);
	if tg_op = 'UPDATE' then
		new.updated_at := now();
	end if;
	return new;
end $$;
create trigger companies_before_write before insert or update on companies
	for each row execute function companies_before_write();

