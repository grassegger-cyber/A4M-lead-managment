-- ---------- phones ----------
create table company_phones (
	id bigint generated always as identity primary key,
	ico char(8) not null references companies (ico),
	phone text not null check (phone ~ '^\+[0-9]{8,15}$'),
	is_primary boolean not null default false,
	operator text check (operator in ('VF', 'O2', 'TM', 'jiny')),
	operator_mccmnc text,
	operator_verified_at timestamptz,
	number_type text,
	source text,
	created_at timestamptz not null default now(),
	unique (ico, phone)
);
create index company_phones_ico_idx on company_phones (ico);
create index company_phones_operator_idx on company_phones (operator);
create index company_phones_verified_idx on company_phones (operator_verified_at);
create index company_phones_phone_idx on company_phones (phone);

-- ---------- state history (append-only) ----------
create table company_state_history (
	id bigint generated always as identity primary key,
	ico char(8) not null references companies (ico),
	at timestamptz not null default now(),
	from_state text,
	to_state text not null,
	from_holder text,
	to_holder text,
	reason_code text,
	note text,
	cohort_id integer references cohorts (id),
	source text not null default 'manual' check (source in (
		'import', 'robot', 'siebel', 'semaphore', 'loss_rule', 'allocation', 'manual', 'system')),
	actor_id uuid,
	actor_name text
);
create index company_state_history_ico_idx on company_state_history (ico, at);
create index company_state_history_at_idx on company_state_history (at desc);
create trigger company_state_history_no_change before update or delete on company_state_history
	for each row execute function forbid_change();
create trigger company_state_history_no_truncate before truncate on company_state_history
	for each statement execute function forbid_change();

-- ---------- rep assignments ----------
create table company_assignments (
	id bigint generated always as identity primary key,
	ico char(8) not null references companies (ico),
	sales_rep_id integer not null references sales_reps (id),
	channel text check (channel in ('operatorka', 'cold_call')),
	source text check (source in ('operator_handover', 'cold_call_allocation', 'rotation', 'manual')),
	handed_over_on date,
	round_no smallint not null default 1,
	cohort_id integer references cohorts (id),
	assigned_from date not null,
	assigned_to date,
	end_reason text,
	created_at timestamptz not null default now()
);
create index company_assignments_ico_idx on company_assignments (ico);
create index company_assignments_rep_idx on company_assignments (sales_rep_id);
create index company_assignments_open_idx on company_assignments (sales_rep_id) where assigned_to is null;
