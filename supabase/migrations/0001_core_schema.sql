-- 0001 core schema (scaffold).
-- Plain Postgres SQL: runs locally in PGlite and can later be pushed to Supabase unchanged.
-- Local variant note: there is no `users` table yet (single local password), so the
-- actor_id / updated_by / created_by uuid columns carry no foreign key.

create extension if not exists pg_trgm;
create extension if not exists unaccent;

-- Normalises text for diacritics-insensitive search (used for companies.name_search).
create or replace function search_norm(input text) returns text
language sql stable as $$ select lower(unaccent(coalesce(input, ''))) $$;

-- Shared guard for append-only tables (row level and TRUNCATE).
create or replace function forbid_change() returns trigger
language plpgsql as $$
begin
	raise exception 'Table % is append-only (% is not allowed)', tg_table_name, tg_op
		using errcode = 'P0001';
end $$;

-- ---------- settings ----------
create table settings (
	key text primary key,
	value jsonb,
	default_value jsonb,
	value_type text not null check (value_type in ('number', 'text', 'boolean', 'list', 'map')),
	group_key text not null,
	label_cs text not null,
	help_cs text,
	sort_order integer not null default 0,
	updated_at timestamptz not null default now(),
	updated_by uuid
);
create index settings_group_idx on settings (group_key, sort_order);

-- ---------- state machine ----------
create table state_transitions (
	from_state text not null,
	to_state text not null,
	enabled boolean not null default true,
	manual_allowed boolean not null default true,
	note_required boolean not null default false,
	label_cs text not null,
	updated_at timestamptz not null default now(),
	updated_by uuid,
	primary key (from_state, to_state)
);

-- ---------- audit log (append-only) ----------
create table audit_log (
	id bigint generated always as identity primary key,
	at timestamptz not null default now(),
	actor_id uuid,
	actor_name text,
	action text not null,
	entity text,
	entity_id text,
	description text,
	details jsonb,
	ip text,
	user_agent text
);
create index audit_log_at_idx on audit_log (at desc);
create index audit_log_action_idx on audit_log (action);
create index audit_log_entity_idx on audit_log (entity, entity_id);
create trigger audit_log_no_change before update or delete on audit_log
	for each row execute function forbid_change();
create trigger audit_log_no_truncate before truncate on audit_log
	for each statement execute function forbid_change();

-- ---------- sessions (local login) ----------
create table sessions (
	id bigint generated always as identity primary key,
	token_hash text not null unique,
	created_at timestamptz not null default now(),
	expires_at timestamptz not null,
	last_seen_at timestamptz,
	revoked_at timestamptz,
	ip text,
	user_agent text
);
create index sessions_expires_idx on sessions (expires_at);

-- ---------- sales reps and cohorts (minimal, per proposal 4.9 and 4.5) ----------
create table sales_reps (
	id integer generated by default as identity primary key,
	name text not null,
	siebel_login text unique,
	raynet_user_id bigint unique,
	rep_type text check (rep_type in ('jezdi', 'online')),
	home_region_code text,
	active boolean not null default true,
	limit_fo integer,
	limit_po integer,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
